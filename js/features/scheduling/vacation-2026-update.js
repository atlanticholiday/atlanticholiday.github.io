function normalizeMatchValue(value) {
    return String(value || '')
        .normalize('NFD')
        .replace(/[\u0300-\u036f]/g, '')
        .trim()
        .toLowerCase()
        .replace(/[^a-z0-9]/g, '');
}

export function getVacationSourceStaffNumber(code) {
    const match = String(code || '').match(/^\d+/);
    return match ? Number(match[0]) : null;
}

export function countCalendarDaysInRanges(ranges = []) {
    return ranges.reduce((total, [startDate, endDate]) => {
        const start = new Date(`${startDate}T00:00:00Z`);
        const end = new Date(`${endDate}T00:00:00Z`);
        if (Number.isNaN(start.getTime()) || Number.isNaN(end.getTime()) || start > end) return total;
        return total + Math.floor((end - start) / 86400000) + 1;
    }, 0);
}

export function buildVacation2026UpdatePlan(employees = []) {
    const claimedEmployeeIds = new Set();
    const unmatched = [];
    const ambiguous = [];
    const items = [];

    VACATION_2026_SOURCE_ROWS.forEach((sourceRow) => {
        const sourceStaffNumber = getVacationSourceStaffNumber(sourceRow.code);
        const normalizedName = normalizeMatchValue(sourceRow.name);
        const staffMatches = employees.filter((employee) => Number(employee?.staffNumber) === sourceStaffNumber);
        const nameMatches = employees.filter((employee) => normalizeMatchValue(employee?.name) === normalizedName);
        const matches = staffMatches.length === 1 ? staffMatches : nameMatches;

        if (matches.length !== 1 || claimedEmployeeIds.has(matches[0]?.id)) {
            if (matches.length > 1) ambiguous.push(sourceRow.name);
            else unmatched.push(sourceRow.name);
            return;
        }

        const employee = matches[0];
        claimedEmployeeIds.add(employee.id);
        items.push({
            employee,
            sourceRow,
            openingAllowance: sourceRow.totalEntitlement - sourceRow.usedThrough2025,
            usageAdjustment: Number(sourceRow.usageAdjustment || 0),
            ranges: sourceRow.ranges.map(([startDate, endDate]) => ({ startDate, endDate }))
        });
    });

    return { items, unmatched, ambiguous };
}
